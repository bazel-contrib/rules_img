// Package isocstream builds an ISO 9660 image together with a compact stream
// of it (see docs/compact-stream.md).
//
// The compact stream represents the image as a small file plus the contents of
// the files inside it: every file of at least a minimum size is replaced by a
// reference to its content in a content-addressed store, and everything else
// (the volume descriptors, the directories, the Rock Ridge and UDF metadata,
// small files, padding and, for now, runs of zeros) stays inline. Because
// [iso9660] stores each file in one contiguous, block-aligned extent, the
// references line up with the files of the image.
package isocstream

import (
	"errors"
	"fmt"
	"io"

	"github.com/bazel-contrib/rules_img/img_tool/pkg/compactstream"
	"github.com/bazel-contrib/rules_img/img_tool/pkg/fs/iso9660"
)

// DefaultMinSize is the size from which files are replaced by references
// unless [Options.MinSize] says otherwise. It matches the default inline
// threshold of layers.
const DefaultMinSize = 4096

// Image is where the image is built. The compact stream is generated by
// reading the finished image back.
type Image interface {
	io.WriterAt
	io.ReaderAt
}

// Options configures the compact stream.
type Options struct {
	// MinSize is the smallest file that is replaced by a reference. Smaller
	// files stay inline. Zero means [DefaultMinSize].
	MinSize int64
}

// Build writes the image of b to image and the compact stream of it to stream.
// The builder must have been created with [iso9660.Options.DigestFiles]. With
// [iso9660.Options.DigestImage] as well, the image is not hashed again and the
// files that become references are not read back.
//
// The compact stream is only complete together with the content-addressed
// blobs of the referenced files, which the caller already has: they are the
// files that went into the image. A file whose stored content is not the file
// that went in -- a boot image whose boot information table was patched -- has
// no digest and stays inline.
func Build(b *iso9660.Builder, image Image, stream io.Writer, opts Options) (*iso9660.Info, error) {
	minSize := opts.MinSize
	if minSize <= 0 {
		minSize = DefaultMinSize
	}

	info, err := b.Build(image)
	if err != nil {
		return nil, err
	}
	var ranges []compactstream.Range
	for _, f := range info.Files {
		if f.Patched {
			// The stored bytes are not the file that went in, so no blob of
			// the content-addressed store holds them.
			continue
		}
		if f.Digest == nil {
			return nil, errors.New("isocstream: the builder does not record file digests, set iso9660.Options.DigestFiles")
		}
		ranges = append(ranges, compactstream.Range{Offset: f.Offset, Size: f.Size, Digest: f.Digest})
	}

	w := compactstream.NewWriter(stream, compactstream.HashAlgoSHA256, 32,
		compactstream.StreamCompressionZstd, compactstream.OriginalCompressionInfo{Compression: compactstream.OriginalCompressionNone}, minSize)
	defer w.Abort() // releases the incremental compressor if we return early
	w.SetContentFormat(compactstream.ContentFormatIso9660)
	if err := w.CompressIncrementally(); err != nil {
		return nil, err
	}
	// With the digest of the image from the builder, the referenced files do
	// not have to be read back.
	if err := compactstream.WriteImageKnownDigest(w, io.NewSectionReader(image, 0, info.Size), info.Size, ranges, minSize, info.Digest); err != nil {
		return nil, err
	}
	if err := w.Close(); err != nil {
		return nil, fmt.Errorf("isocstream: writing compact stream: %w", err)
	}
	return info, nil
}
